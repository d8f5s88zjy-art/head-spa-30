def main(cesta, polozky_json):
    ids = {p['id'] for p in json.load(open(polozky_json))['polozky']}
    riadky, videne = [], set()
    for jazyk, sada in SADY:
        for otazka, oc in sada:
            assert oc in (O, B) or oc in ids, (jazyk, otazka, oc)
            assert (jazyk, otazka) not in videne, (jazyk, otazka)
            videne.add((jazyk, otazka))
            riadky.append({'jazyk': jazyk, 'otazka': otazka, 'ocakavane': oc})
    if os.path.exists(cesta) and not os.path.exists(cesta + '.pred-k4'):
        shutil.copyfile(cesta, cesta + '.pred-k4')
    with open(cesta, 'w', encoding='utf-8') as f:
        for r in riadky:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    pocty = {}
    for r in riadky:
        pocty[r['jazyk']] = pocty.get(r['jazyk'], 0) + 1
    print(len(riadky), pocty)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
