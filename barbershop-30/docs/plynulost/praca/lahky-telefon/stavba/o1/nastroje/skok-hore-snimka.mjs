import { createRequire } from 'node:module';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
const [ROOT, OUT] = process.argv.slice(2);
const { startStaticServer } = await import(ROOT + '/source/shot.mjs');
const srv = await startStaticServer(ROOT);
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, colorScheme: 'dark' });
const page = await ctx.newPage();
let armed = false;
await page.route(/assets\/img\/film\/.*-m-\d+\.(avif|webp)/, async (r) => { if (armed && !/rohozka/.test(r.request().url())) await new Promise((s) => setTimeout(s, 2500)); r.continue().catch(() => {}); });
await page.goto(srv.origin + '/index.html', { waitUntil: 'load' });
await page.waitForTimeout(2500);
const y = (i) => page.evaluate((i) => { const el = document.querySelectorAll('.film-shot.is-title')[i]; const r = el.getBoundingClientRect(); return Math.round(r.top + scrollY + Math.min(r.height * 0.3, 600)); }, i);
await page.evaluate((v) => scrollTo({ top: v, behavior: 'instant' }), await y(6));
await page.waitForTimeout(4000);
armed = true;
await page.evaluate((v) => scrollTo({ top: v, behavior: 'instant' }), await y(2));
await page.waitForTimeout(500);
await page.screenshot({ path: OUT + '/skok-hore-500ms.png' });
const lum = await page.evaluate(() => [...document.querySelectorAll('.film-shot.is-title .film-still')].map((s, i) => { const c = getComputedStyle(s); return i + ':' + c.display + '/' + c.visibility + '/' + c.opacity; }).join(' '));
console.log(lum);
await browser.close(); srv.server.close();
